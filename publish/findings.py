# Writes docs/findings.md from the dbt analyses in transform/analyses/: a table per analysis, each
# followed by the compiled SQL that reproduces it. Formatting happens in the SQL, so every table
# is exactly what its query returns. `make findings` compiles the analyses first.

import logging
import re
import sys

import duckdb

from ingest.paths import DOCS, TRANSFORM, WAREHOUSE

log = logging.getLogger("findings")

ANALYSES = TRANSFORM / "analyses"
COMPILED = TRANSFORM / "target" / "compiled" / "gph" / "analyses"
OUT = DOCS / "findings.md"
# Empty until Spring 2027 registration opens on 2026-11-02 and snapshots after it exist.
MAY_BE_EMPTY = {"f6d_5_registration_changes", "f6d_6_registration_after_open"}
NUMBER = re.compile(r"^[+-]?[\d,]+(\.\d+)?(%| pts)?$")
HEADER = (
    "# Findings\n\n"
    "Generated by `make findings` from transform/analyses/ against warehouse/gph.duckdb. "
    "Edit the SQL, not this file.\n"
)


def title(source):
    first = source.read_text().splitlines()[0]
    assert first.startswith("-- "), f"{source.name}: the first line must be a '-- ' title"
    return first.removeprefix("-- ")


def compiled_sql(source):
    path = COMPILED / source.name
    assert path.exists(), f"{path.relative_to(TRANSFORM)} is missing; run make findings"
    assert path.stat().st_mtime >= source.stat().st_mtime, f"{path.name} is stale; recompile"
    # Unqualified names read like the models and still run against gph.duckdb.
    return path.read_text().replace('"gph"."main".', "").strip()


def cell(value):
    return "" if value is None else str(value).replace("|", "\\|")


def render_table(columns, rows):
    # Right-align columns that hold only numbers, so digits line up.
    numeric = [
        bool(rows) and all(NUMBER.match(cell(r[i])) for r in rows if r[i] is not None)
        for i in range(len(columns))
    ]
    rule = "|" + "|".join("---:" if n else "---" for n in numeric) + "|"
    lines = ["| " + " | ".join(columns) + " |", rule]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def section(source, con):
    sql = compiled_sql(source)
    result = con.sql(sql)
    columns, rows = result.columns, result.fetchall()
    assert rows or source.stem in MAY_BE_EMPTY, f"{source.name} returned no rows"
    log.info("%s: %d rows", source.stem, len(rows))
    return (
        f"## {title(source)}\n\n{render_table(columns, rows)}\n\n"
        f"<details><summary>SQL</summary>\n\n```sql\n{sql}\n```\n\n</details>\n"
    )


def main():
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    sources = sorted(ANALYSES.glob("*.sql"))
    assert sources, f"no analyses in {ANALYSES.relative_to(TRANSFORM.parent)}"
    con = duckdb.connect(str(WAREHOUSE), read_only=True)
    sections = [section(s, con) for s in sources]
    OUT.write_text(HEADER + "\n" + "\n".join(sections))
    log.info("wrote %s with %d tables", OUT.relative_to(TRANSFORM.parent), len(sections))
    return 0


if __name__ == "__main__":
    sys.exit(main())
