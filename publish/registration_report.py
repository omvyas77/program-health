# Writes reports/registration_watch_2027-sp.md from the exported mart_registration_watch after
# each snapshot: where registration stands, the courses that added sections since it opened, what
# changed since the previous snapshot, and, once the course-page pass has run, closed sections.

import logging
import sys

import pandas as pd

from ingest.paths import MARTS, ROOT
from publish.findings import render_table

log = logging.getLogger("registration_report")

OUT = ROOT / "reports" / "registration_watch_2027-sp.md"
NOTE = (
    "Enrollment status comes from the public course pages, read once a day at 8:14 am Central "
    "with permission from the university's Tech Services. Closed isn't the same as full, and Open "
    "(Restricted) means seats held for certain students; the closed share counts Closed only. A "
    "section added after registration opens can mean demand ran ahead of the schedule; it can "
    "also be a room or staffing change. Primary sections are lectures, lecture-discussions, "
    "online lectures, and seminars, not discussions or labs."
)


def day(value):
    return f"{value:%b} {value.day}, {value.year}"


def status(days, opens):
    if days < 0:
        return f"registration opens in {-days} day{'s' if days != -1 else ''}, on {day(opens)}"
    if days == 0:
        return f"registration opens today, {day(opens)}"
    return f"registration opened {days} day{'s' if days != 1 else ''} ago, on {day(opens)}"


def report(watch):
    watch = watch.assign(
        snapshot_date=pd.to_datetime(watch.snapshot_date), course=watch.subject + " " + watch.number
    )
    dates = sorted(watch.snapshot_date.unique())
    as_of = pd.Timestamp(dates[-1])
    latest = watch[watch.snapshot_date == as_of].sort_values("course")
    days = int(latest.days_since_registration_open.iloc[0])
    opens = as_of - pd.Timedelta(days=days)
    lines = [
        "# Spring 2027 registration watch",
        "",
        f"As of the {day(as_of)} snapshot, {status(days, opens)}. Gies lists "
        f"{int(latest.primary_sections.sum()):,} primary sections across "
        f"{int((latest.primary_sections > 0).sum()):,} courses.",
        "",
        "## Sections added since registration opened",
        "",
    ]
    added = latest[latest.sections_added_since_open > 0]
    if days <= 0:
        lines.append("Registration hasn't opened yet.")
    elif added.empty:
        lines.append("No Gies course has added a primary section since registration opened.")
    else:
        lines.append(
            render_table(
                ["Course", "Primary sections", "Added since registration opened"],
                [
                    (r.course, int(r.primary_sections), int(r.sections_added_since_open))
                    for r in added.itertuples()
                ],
            )
        )
    lines += [""]
    if len(dates) > 1:
        previous = pd.Timestamp(dates[-2])
        lines += [f"## Since the previous snapshot, {day(previous)}", ""]
        moved = latest[
            (latest.sections_added_since_previous > 0)
            | (latest.sections_removed_since_previous > 0)
        ]
        if moved.empty:
            lines.append("No Gies course gained or lost a primary section.")
        else:
            lines.append(
                render_table(
                    ["Course", "Primary sections", "Added", "Removed"],
                    [
                        (
                            r.course,
                            int(r.primary_sections),
                            int(r.sections_added_since_previous),
                            int(r.sections_removed_since_previous),
                        )
                        for r in moved.itertuples()
                    ],
                )
            )
        lines += [""]
    lines += status_lines(watch) + [""]
    lines += [
        NOTE,
        "",
        "Generated by publish/registration_report.py after each daily snapshot.",
        "",
    ]
    return "\n".join(lines)


def status_lines(watch):
    lines = ["## Closed sections", ""]
    known = watch[watch.sections_with_status > 0]
    if known.empty:
        return lines + [
            "Enrollment status from the Gies course pages starts with the Oct 28, 2026 pass, read "
            "at 8:14 am Central."
        ]
    dates = sorted(known.snapshot_date.unique())
    today = known[known.snapshot_date == dates[-1]].set_index("course")
    closed, total = int(today.closed_sections.sum()), int(today.sections_with_status.sum())
    restricted = int(today.restricted_sections.sum())
    lines.append(
        f"As of the {day(pd.Timestamp(dates[-1]))} status pass, {closed:,} of {total:,} Gies "
        f"primary sections ({100 * closed / total:.1f}%) were closed, and "
        f"{restricted:,} {'was' if restricted == 1 else 'were'} Open (Restricted)."
    )
    full = today[today.closed_sections == today.sections_with_status]
    if not full.empty:
        rows = [(c, int(r.sections_with_status)) for c, r in full.sort_index().iterrows()]
        lines += ["", render_table(["Course with every primary section closed", "Sections"], rows)]
    if len(dates) > 1:
        before = known[known.snapshot_date == dates[-2]].set_index("course")
        joined = today.join(before[["closed_sections"]], rsuffix="_before", how="left")
        moved = joined[
            (joined.closed_sections != joined.closed_sections_before.fillna(0))
            | (joined.reopened_since_previous.fillna(0) > 0)
        ]
        lines += ["", f"Since the {day(pd.Timestamp(dates[-2]))} pass:", ""]
        if moved.empty:
            lines.append("No Gies course's closed count changed.")
        else:
            rows = [
                (
                    c,
                    int(0 if pd.isna(r.closed_sections_before) else r.closed_sections_before),
                    int(r.closed_sections),
                    int(0 if pd.isna(r.reopened_since_previous) else r.reopened_since_previous),
                )
                for c, r in moved.sort_index().iterrows()
            ]
            lines.append(render_table(["Course", "Closed before", "Closed now", "Reopened"], rows))
    return lines


def main():
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    watch = pd.read_parquet(MARTS / "mart_registration_watch.parquet")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(report(watch))
    log.info("wrote %s", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
